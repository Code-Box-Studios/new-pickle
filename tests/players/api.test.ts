import { beforeEach, describe, expect, it, vi } from "vitest";
import { NextRequest } from "next/server";
import { prisma, resetDb } from "../db";
import { seedConfirmedBooking, seedCustomer } from "../factories";
vi.mock("@/lib/auth/session", () => ({ getSession: vi.fn() }));
import { getSession } from "@/lib/auth/session";
import { GET, POST, PATCH } from "@/app/api/players/[...path]/route";
import { createInvitation } from "@/lib/players/invitations";
import { gameSetup, finish } from "./fixtures";
beforeEach(async () => { await resetDb(); vi.clearAllMocks(); vi.mocked(getSession).mockResolvedValue(null); });
const context = (path: string) => ({ params: Promise.resolve({ path: path.split("/") }) });
const req = (path: string, body: unknown, origin = "http://localhost", method = "POST") => new NextRequest(`http://localhost/api/players/${path}`, { method, headers: { origin, "content-type": "application/json" }, body: JSON.stringify(body) });
describe("Player HTTP privacy and consent", () => {
  it("requires a submission ID and returns the original game when HTTP creation is retried", async () => {
    const o = await gameSetup(); await finish(o);
    vi.mocked(getSession).mockResolvedValue({ id:o.customerId,email:null,role:"CUSTOMER" });
    const path = `bookings/${o.bookingId}/matches`;
    const input = {format:"SINGLES",teamA:[o.self],teamB:[o.g1],winner:"A"};
    expect((await POST(req(path,input), context(path))).status).toBe(400);
    const body = {...input,submissionId:"721df0ac-85ed-4732-ac9f-859ae8cbb383"};
    const first = await POST(req(path,body), context(path));
    const retry = await POST(req(path,body), context(path));
    expect(first.status).toBe(201);
    expect(retry.status).toBe(201);
    expect(await retry.json()).toEqual(await first.json());
    expect(await prisma.playerMatch.count()).toBe(1);
    expect((await POST(req(path,{...body,submissionId:"bad"}), context(path))).status).toBe(400);
  });
  it("requires a session for private data and same-origin bounded JSON writes", async () => {
    expect((await GET(new NextRequest("http://localhost/api/players/me"), context("me"))).status).toBe(401);
    const b = await seedConfirmedBooking();
    vi.mocked(getSession).mockResolvedValue({ id: b.customerId, email: null, role: "CUSTOMER" });
    expect((await POST(req(`bookings/${b.bookingId}/guests`, { nickname: "Guest" }, "https://evil.test"), context(`bookings/${b.bookingId}/guests`))).status).toBe(403);
    expect((await POST(req(`bookings/${b.bookingId}/guests`, { nickname: "x".repeat(13000) }), context(`bookings/${b.bookingId}/guests`))).status).toBe(413);
    expect((await PATCH(req("me", { displayName: "Me", skillLevel: null, userId: b.ownerId, role: "ADMIN" }, "http://localhost", "PATCH"), context("me"))).status).toBe(200);
    expect((await prisma.user.findUniqueOrThrow({ where: { id: b.customerId } })).role).toBe("CUSTOMER");
    expect(await prisma.playerProfile.findUnique({ where: { userId: b.ownerId } })).toBeNull();
    const bad = new NextRequest("http://localhost/api/players/me", { method: "PATCH", headers: { origin: "http://localhost" }, body: "{" });
    expect((await PATCH(bad, context("me"))).status).toBe(400);
  });
  it("ignores forged player identity, and participation never grants booking/payment access", async () => {
    const b = await seedConfirmedBooking(); const u = await seedCustomer();
    const i = await createInvitation(b.customerId, b.bookingId);
    vi.mocked(getSession).mockResolvedValue({ id: u.id, email: u.email, role: "CUSTOMER" });
    const res = await POST(req("invitations/accept", { token: i.token, nickname: "Me", userId: b.ownerId }), context("invitations/accept"));
    expect(res.status).toBe(200);
    expect(await prisma.bookingParticipant.count({ where: { userId: u.id } })).toBe(1);
    expect(await prisma.bookingParticipant.count({ where: { userId: b.ownerId } })).toBe(0);
    const roster = await GET(new NextRequest(`http://localhost/api/players/bookings/${b.bookingId}`), context(`bookings/${b.bookingId}`));
    expect(roster.status).toBe(200);
    expect(roster.headers.get("cache-control")).toContain("private");
    const body = JSON.stringify(await roster.json());
    expect(body).not.toContain("customerEmail"); expect(body).not.toContain(b.reference);
    const stranger = await seedCustomer();
    vi.mocked(getSession).mockResolvedValue({ id: stranger.id, email: stranger.email, role: "ADMIN" });
    expect((await GET(new NextRequest(`http://localhost/api/players/bookings/${b.bookingId}`), context(`bookings/${b.bookingId}`))).status).toBe(403);
  });
  it("keeps invitation capability out of server URLs across sign-in", async () => {
    const b = await seedConfirmedBooking(); const i = await createInvitation(b.customerId, b.bookingId);
    const lookup = await POST(req("invitations/lookup", { token: i.token }), context("invitations/lookup"));
    expect(lookup.status).toBe(200);
    const remembered = await POST(req("invitations/remember", { token: i.token }), context("invitations/remember"));
    expect(remembered.status).toBe(200);
    const cookie = remembered.headers.get("set-cookie")!;
    expect(cookie).toContain("HttpOnly"); expect(cookie).toContain("SameSite=lax"); expect(cookie).toContain("Path=/players/invite"); expect(cookie).toContain("Max-Age=600");
    const u = await seedCustomer();
    vi.mocked(getSession).mockResolvedValue({ id: u.id, email: u.email, role: "CUSTOMER" });
    const accepted = await POST(req("invitations/accept", { token: i.token }), context("invitations/accept"));
    expect(accepted.headers.get("set-cookie")).toContain("Max-Age=0");
  });
});
